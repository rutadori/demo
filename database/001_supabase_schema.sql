-- 일본 부동산 앱 전용 PostgreSQL 스키마입니다. 기존 public·auth 테이블은 수정하지 않습니다.
-- 원본 프로젝트: Supabase ujwzjjoqyfazdgmfdcoj. 최초 적용용이며 기존 스키마와 충돌하면 중단합니다.
CREATE SCHEMA house_app;
COMMENT ON SCHEMA house_app IS '부동산 매물 앱 전용. Spring 서버에서 JDBC로 접근하며 Data API에는 노출하지 않습니다.';

CREATE TABLE house_app.property_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(50) COLLATE "C" NOT NULL,
    source_name VARCHAR(100) NOT NULL,
    base_url VARCHAR(512) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT timezone('Asia/Tokyo', CURRENT_TIMESTAMP),
    CONSTRAINT uk_property_source_code UNIQUE (source_code)
);
COMMENT ON TABLE house_app.property_source IS '매물 원본 사이트. 수집 중지 여부는 재등록 때 보존합니다.';
COMMENT ON COLUMN house_app.property_source.id IS '출처 번호. MySQL에서 사용한 기존 번호도 이전합니다.';
COMMENT ON COLUMN house_app.property_source.is_enabled IS 'TRUE 수집 사용, FALSE 수집 중지. 기존 매물 노출 여부와 구분합니다.';

CREATE TABLE house_app.property_listing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    source_listing_key VARCHAR(200) COLLATE "C" NOT NULL,
    title VARCHAR(255) NOT NULL,
    original_url VARCHAR(2048) NOT NULL,
    prefecture VARCHAR(50),
    city VARCHAR(100),
    address VARCHAR(500),
    rent_yen INTEGER,
    management_fee_yen INTEGER,
    layout VARCHAR(30),
    area_m2 NUMERIC(8,2),
    station_name VARCHAR(100),
    walk_minutes SMALLINT,
    image_url VARCHAR(2048),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    last_seen_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT timezone('Asia/Tokyo', CURRENT_TIMESTAMP),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT timezone('Asia/Tokyo', CURRENT_TIMESTAMP),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT timezone('Asia/Tokyo', CURRENT_TIMESTAMP),
    CONSTRAINT uk_property_listing_source UNIQUE (source_id, source_listing_key),
    CONSTRAINT fk_property_listing_source FOREIGN KEY (source_id)
        REFERENCES house_app.property_source(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_property_listing_area CHECK (area_m2 > 0),
    CONSTRAINT chk_property_listing_management_fee CHECK (management_fee_yen >= 0),
    CONSTRAINT chk_property_listing_rent CHECK (rent_yen >= 0),
    CONSTRAINT chk_property_listing_status CHECK (status IN ('ACTIVE','INACTIVE','UNKNOWN')),
    CONSTRAINT chk_property_listing_walk CHECK (walk_minutes >= 0)
);
COMMENT ON TABLE house_app.property_listing IS '원본 사이트별 매물. 사진 파일은 저장하지 않고 image_url 문자열만 저장합니다.';
COMMENT ON COLUMN house_app.property_listing.source_listing_key IS '출처별 원본 URL의 고유 키. 같은 출처의 같은 키는 중복 삽입 대신 갱신합니다.';
COMMENT ON COLUMN house_app.property_listing.image_url IS '사진이 있는 외부 주소. Supabase Storage에 사진 파일을 복사하지 않습니다.';
COMMENT ON COLUMN house_app.property_listing.created_at IS '우리 앱 최초 저장 시각. 원본 게시 시각이 아닙니다. 기존 일본 표준시 LocalDateTime을 보존합니다.';
COMMENT ON COLUMN house_app.property_listing.last_seen_at IS '원본에서 마지막 확인한 시각. 현재 정보의 정확성 보증과는 구분합니다.';

CREATE INDEX idx_property_listing_search ON house_app.property_listing(status, prefecture, rent_yen);
CREATE INDEX idx_property_listing_source_seen ON house_app.property_listing(source_id, last_seen_at);

-- MySQL의 ON UPDATE CURRENT_TIMESTAMP에 해당합니다. 타임존 없는 기존 시각의 의미를 유지합니다.
CREATE FUNCTION house_app.touch_listing_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    NEW.updated_at := timezone('Asia/Tokyo', CURRENT_TIMESTAMP);
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_property_listing_updated_at BEFORE UPDATE ON house_app.property_listing
FOR EACH ROW EXECUTE FUNCTION house_app.touch_listing_updated_at();

-- 로그인 암호는 별도 보안 단계에서 지정합니다. 스키마 파일에는 비밀정보를 넣지 않습니다.
CREATE ROLE house_app_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
GRANT CONNECT ON DATABASE postgres TO house_app_runtime;
GRANT USAGE ON SCHEMA house_app TO house_app_runtime;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA house_app TO house_app_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA house_app TO house_app_runtime;
ALTER ROLE house_app_runtime SET search_path TO house_app;

-- 새 영역의 API 접근을 기본적으로 닫습니다. 기존 public 테이블의 권한은 바꾸지 않습니다.
REVOKE ALL ON SCHEMA house_app FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA house_app FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA house_app FROM PUBLIC, anon, authenticated;
ALTER TABLE house_app.property_source ENABLE ROW LEVEL SECURITY;
ALTER TABLE house_app.property_listing ENABLE ROW LEVEL SECURITY;

CREATE POLICY runtime_source_select ON house_app.property_source FOR SELECT TO house_app_runtime USING (TRUE);
CREATE POLICY runtime_source_insert ON house_app.property_source FOR INSERT TO house_app_runtime WITH CHECK (TRUE);
CREATE POLICY runtime_source_update ON house_app.property_source FOR UPDATE TO house_app_runtime USING (TRUE) WITH CHECK (TRUE);
CREATE POLICY runtime_listing_select ON house_app.property_listing FOR SELECT TO house_app_runtime USING (TRUE);
CREATE POLICY runtime_listing_insert ON house_app.property_listing FOR INSERT TO house_app_runtime WITH CHECK (TRUE);
CREATE POLICY runtime_listing_update ON house_app.property_listing FOR UPDATE TO house_app_runtime USING (TRUE) WITH CHECK (TRUE);
